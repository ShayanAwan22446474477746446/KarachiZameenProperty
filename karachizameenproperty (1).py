@app.route('/predict', methods=['GET'])
def predict_price():
    try:
        bedrooms = float(request.args.get('bedrooms', 0))
        bathrooms = float(request.args.get('bathrooms', 0))
        area = float(request.args.get('area', 1))
        property_type = request.args.get('property_type', 'House')

        if property_type not in le.classes_:
            return jsonify({'error': 'Invalid type'}), 400

        type_encoded = le.transform([property_type])[0]
        features = scaler.transform([[bedrooms, bathrooms, area, type_encoded]])
        prediction = model.predict(features)[0]
        return jsonify({'predicted_price': round(prediction, 2), 'currency': 'PKR'})
    except Exception as e:
        return jsonify({'error': str(e)}), 500

