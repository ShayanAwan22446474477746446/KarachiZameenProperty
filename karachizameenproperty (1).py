model = None
le = None
scaler = None

def load_model_and_encoder():
    global model, le, scaler
    try:
        with open('property_price_model.pkl', 'rb') as f:
            model = pickle.load(f)
        with open('label_encoder.pkl', 'rb') as f:
            le = pickle.load(f)
        with open('scaler.pkl', 'rb') as f:
            scaler = pickle.load(f)
        print("Model, encoder, and scaler loaded successfully.")
        return True
    except FileNotFoundError:
        print("Model files not found. Training model...")
        return False

def train_and_save_model():
    global model, le, scaler
    try:
        df = pd.read_csv('karachi-pakistan-property-prices-2023.csv')
    except FileNotFoundError:
        print("CSV file not found.")
        return False

    df = df[['price', 'type', 'bedrooms', 'bathrooms', 'area']].copy()
    df['area'] = df['area'].astype(str).str.replace(' Sq. Yd.', '', regex=False)
    df['area'] = pd.to_numeric(df['area'], errors='coerce')
    df.dropna(inplace=True)

    # Convert price
    def convert_price(price_str):
        if isinstance(price_str, str) and 'Crore' in price_str:
            return float(price_str.replace('Crore', '').strip()) * 1e7
        elif isinstance(price_str, str) and 'Lakh' in price_str:
            return float(price_str.replace('Lakh', '').strip()) * 1e5
        else:
            return float(price_str) if pd.notna(price_str) else np.nan
    df['price'] = df['price'].apply(convert_price)
    df.dropna(subset=['price'], inplace=True)

    # Outlier removal
    df = df[(df['price'] > 0) & (df['area'] > 0)]

    le = LabelEncoder()
    df['type_encoded'] = le.fit_transform(df['type'])

    X = df[['bedrooms', 'bathrooms', 'area', 'type_encoded']]
    y = df['price']

    scaler = StandardScaler()
    X_scaled = scaler.fit_transform(X)

    X_train, X_test, y_train, y_test = train_test_split(X_scaled, y, test_size=0.2, random_state=42)

    model = RandomForestRegressor(n_estimators=200, max_depth=10, random_state=42)
    model.fit(X_train, y_train)

    y_pred = model.predict(X_test)
    mae = mean_absolute_error(y_test, y_pred)
    r2 = r2_score(y_test, y_pred)
    print(f'MAE: {mae}, R²: {r2}')

    with open('property_price_model.pkl', 'wb') as f:
        pickle.dump(model, f)
    with open('label_encoder.pkl', 'wb') as f:
        pickle.dump(le, f)
    with open('scaler.pkl', 'wb') as f:
        pickle.dump(scaler, f)
    print("Model saved.")
    return True

